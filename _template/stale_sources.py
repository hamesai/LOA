#!/usr/bin/env python3
"""Which cited web sources need reopening: a to-do list, worst first.

    python _template/stale_sources.py <course> [--months 6]     print the list and write courses/<course>/docs/STALE-SOURCES.md
    python _template/stale_sources.py --all [--months 6]        every course, plus a one-line summary each
    python _template/stale_sources.py <course> --backfill       set d: only where the ref's own text records when it was read,
                                                                opened, checked or accessed (for example "read in full, 12/10/2026")

A ref's d: "DD/MM/YYYY" is the date someone last opened the source and checked what the course takes from it. "Last updated"
dates in a ref's text are the publisher's, not ours, and are never used. Ingested books (refs with b:) are left out: their
reading is recorded by source_read.py.

Time-sensitive sources (law, tax, prices, rates, official guidance) come first, because they go out of date. After reopening a
source and checking the course's claims against it, set its d: to that day.
"""
import argparse, json, os, re, subprocess, sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OFFICIAL = re.compile(r"(gov\.uk|legislation\.gov|fca\.org|hmrc|moneyhelper|ons\.gov|food\.gov|nhs\.uk|hse\.gov|ofgem|ofcom|citizensadvice|"
                      r"which\.co\.uk|nature\.scot|naturalresources\.wales|outdooraccess-scotland|europa\.eu|who\.int|cdc\.gov|usda\.gov)", re.I)
TOPIC = re.compile(r"\b(tax|vat|allowance|threshold|£|\$|price|prices|rate|rates|fee|fees|law|legal|regulation|regulations|rule|rules|"
                   r"licen[cs]e|permit|act \d{4}|bye-?law|limit|limits|isa|pension|benefit|interest|inflation|duty|compliance)\b", re.I)
READ_AT = re.compile(r"\b(read|opened|checked|accessed|fetched|retrieved|viewed|reading record)\b[^\"]{0,40}?(\d\d)/(\d\d)/(20\d\d)", re.I)
REFS_JS = ("const fs=require('fs'),vm=require('vm'),w={};w.window=w;for(const f of process.argv.slice(1)){try{vm.runInNewContext("
           "fs.readFileSync(f,'utf8'),w)}catch(e){}}console.log(JSON.stringify(w.COURSE_REFS||{}))")


def ref_files(cid):
    D = ROOT / "courses" / cid
    return [p for p in [D / "course-refs.js", D / ("course-%s-refs.js" % cid)] if p.exists()]


def load(cid):
    files = ref_files(cid)
    if not files:
        return {}, set(), files
    refs = json.loads(subprocess.run(["node", "-e", REFS_JS] + [str(f) for f in files], capture_output=True, text=True, encoding="utf-8", check=True).stdout)
    cited = set()
    for f in (ROOT / "courses" / cid / "modules").glob("*.js"):
        cited |= set(re.findall(r"\{\{([a-z0-9-]+)\}\}", f.read_text(encoding="utf-8")))
    return refs, cited, files


def parse_d(s):
    m = re.match(r"(\d\d)/(\d\d)/(\d{4})$", s or "")
    return date(int(m.group(3)), int(m.group(2)), int(m.group(1))) if m else None


def rows(cid, months):
    refs, cited, _ = load(cid)
    out = []
    for k in sorted(cited):
        r = refs.get(k)
        if not r or r.get("b") or not r.get("u"):
            continue
        when = parse_d(r.get("d"))
        age = (date.today() - when).days if when else None
        timely = bool(OFFICIAL.search(r.get("u", "")) or TOPIC.search(r.get("t", "")))
        due = when is None or age > months * 30.5
        out.append(dict(key=k, t=r.get("t", ""), u=r["u"], d=r.get("d"), age=age, timely=timely, due=due))
    out.sort(key=lambda x: (not x["due"], not x["timely"], -(x["age"] if x["age"] is not None else 10 ** 6), x["key"]))
    return out


def write(cid, months):
    R = rows(cid, months)
    due = [r for r in R if r["due"]]
    t_due = [r for r in due if r["timely"]]
    L = ["<!-- generated by _template/stale_sources.py; rerun it after reopening sources -->",
         "# Sources to reopen: %s" % cid, "",
         "Updated %s. %d cited web sources; %d never checked or last checked over %d months ago, %d of them time-sensitive (law, tax, prices, official guidance)." % (
             date.today().strftime("%d/%m/%Y"), len(R), len(due), months, len(t_due)), "",
         "Reopen each source, check what the course takes from it, then set its `d:` to that day in the course refs file.", "",
         "| Ref | Time-sensitive | Last checked | Source |", "|---|---|---|---|"]
    for r in due:
        L.append("| %s | %s | %s | [%s](%s) |" % (r["key"], "yes" if r["timely"] else "", r["d"] or "never", r["t"][:70].replace("|", "/"), r["u"]))
    out = ROOT / "courses" / cid / "docs" / "STALE-SOURCES.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    return R, due, t_due, out


def backfill(cid):
    """Adds d: to refs whose own text says when they were read or opened. Never invents a date."""
    refs, cited, files = load(cid)
    n = 0
    for f in files:
        s = f.read_text(encoding="utf-8")
        lines = s.splitlines(keepends=True)
        for i, line in enumerate(lines):
            m = re.match(r'(\s*"([a-z0-9-]+)"\s*:\s*\{)(.*)$', line)
            if not m or re.search(r'(\bd|"d")\s*:\s*"\d\d/\d\d/\d{4}"', line):
                continue
            r = refs.get(m.group(2), {})
            if r.get("b") or not r.get("u"):
                continue
            hits = [h for h in READ_AT.finditer(r.get("t", ""))]
            if not hits:
                continue
            when = max(date(int(h.group(4)), int(h.group(3)), int(h.group(2))) for h in hits)
            if when > date.today():
                continue
            lines[i] = m.group(1) + ' d: "%s",' % when.strftime("%d/%m/%Y") + m.group(3) + ("\n" if not m.group(3).endswith("\n") and line.endswith("\n") else "")
            n += 1
            print("  %s  d: %s  (from: %s)" % (m.group(2), when.strftime("%d/%m/%Y"), hits[-1].group(0)[:60]))
        f.write_text("".join(lines), encoding="utf-8")
    print("%s: %d checked date(s) added from the refs' own reading notes" % (cid, n))
    return n


if __name__ == "__main__":
    for s in (sys.stdout, sys.stderr):
        try:
            s.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("course", nargs="?")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--months", type=int, default=6)
    ap.add_argument("--backfill", action="store_true")
    a = ap.parse_args()
    if not (a.all or a.course):
        sys.exit(__doc__)
    ids = sorted(p.name for p in (ROOT / "courses").iterdir() if (p / "modules").is_dir()) if a.all else [a.course]
    for c in ids:
        if a.backfill:
            backfill(c)
            continue
        R, due, t_due, out = write(c, a.months)
        print("%-22s %3d web sources, %3d to reopen (%d time-sensitive)  -> %s" % (c, len(R), len(due), len(t_due), out.relative_to(ROOT)))
        if not a.all:
            for r in due[:25]:
                print("  %-26s %-4s %-10s %s" % (r["key"], "TIME" if r["timely"] else "", r["d"] or "never", r["u"]))
