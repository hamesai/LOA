#!/usr/bin/env python3
"""Writes courses/<course>/docs/READING-STATE.md: one page that says, for every ingested source, what is read, what is in
progress, what is unread and how many findings are still open. It is built from the read records (read.json, served.json,
skipped.json, findings), so it is always true. Start a session by reading it; never keep this state in memory notes.

    python _template/reading_state.py <course>        write the file and print a one-line summary per source
    python _template/reading_state.py --all           every course with ingested sources

source_read.py rewrites it after every chunk, skip and log, and kit.py ship rewrites it too.
"""
import os, sys
from datetime import date

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import source_lib as S


def dmy(iso):
    iso = (iso or "")[:10]
    return "%s/%s/%s" % (iso[8:10], iso[5:7], iso[:4]) if len(iso) == 10 and iso[4] == "-" else (iso or "never")


def build(cid, quiet=False):
    srcs = S.sources(cid)
    if not srcs:
        return None
    try:
        import source_apply as SA
        allf = SA.all_findings(cid)
    except Exception:
        allf = []
    L = ["<!-- generated by _template/reading_state.py from the read records. Do not edit; it is rewritten after every read. -->",
         "# Reading state: %s" % cid, "",
         "Updated %s. Built from each source's read records, so it is always current." % date.today().strftime("%d/%m/%Y"), "",
         "| Source | Read in full | Skipped | Unread | Words read | In progress | Open findings | Last read |",
         "|---|---|---|---|---|---|---|---|"]
    detail, lines = [], []
    for d, man in srcs:
        nm, sv, st = S.numbers(d, man), S.served(d), S.status(d, man)
        going = [(c, sv[c["file"]]) for c in man["chapters"] if st[c["file"]] == "unread" and c["file"] in sv and 0 < sv[c["file"]].get("done", 0) < sv[c["file"]].get("total", 0)]
        last = max([r.get("at") or r.get("date", "") for r in sv.values()] + [""])
        opn = sum(1 for f in allf if f["book"] == man["key"] and f["state"] == "open")
        pct = round(100 * nm["read"] / max(1, nm["total"]))
        prog = ", ".join("%s chunk %d of %d" % (c["file"], r["done"], r["total"]) for c, r in going) or "none"
        L.append("| %s | %d of %d | %d | %d | %d%% | %s | %d | %s |" % (man["key"], nm["n_read"], nm["n"], nm["n_skipped"], len(nm["unread"]), pct, prog, opn, dmy(last)))
        lines.append("%-22s %3d of %3d read, %3d unread, %3d%% of words, %d open finding(s)%s" % (man["key"], nm["n_read"], nm["n"], len(nm["unread"]), pct, opn, ("; in progress " + prog) if going else ""))
        if nm["unread"]:
            detail.append("### %s: %s" % (man["key"], man.get("title", "")))
            detail.append("")
            for c in nm["unread"]:
                r = sv.get(c["file"])
                tag = (" (chunk %d of %d served)" % (r["done"], r["total"])) if r and 0 < r.get("done", 0) < r.get("total", 0) else ""
                detail.append("- %s  %s, %d words%s" % (c["file"], c["title"], c["words"], tag))
            detail.append("")
    L += ["", "Continue a source with `python _template/source_read.py %s <key> --next` (it finishes a chapter in progress first)." % cid, ""]
    if detail:
        L += ["## Unread chapters", ""] + detail
    out = S.ROOT / "courses" / cid / "docs" / "READING-STATE.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    if not quiet:
        print("wrote %s" % out.relative_to(S.ROOT))
        for l in lines:
            print("  " + l)
    return out


if __name__ == "__main__":
    for s in (sys.stdout, sys.stderr):
        try:
            s.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    ids = sorted(p.name for p in (S.ROOT / "courses").iterdir() if (p / "sources").is_dir()) if sys.argv[1] == "--all" else [sys.argv[1]]
    for c in ids:
        build(c)
